<#
  Deploys the signaling relay to your Cloudflare account (Workers Free plan is enough).
    cd src\SeriesShare\relay
    npx wrangler login        # once
    powershell -ExecutionPolicy Bypass -File deploy.ps1
#>
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
# Embed the viewer page (same file that mpc-share serves locally) as a JS module.
$html = [IO.File]::ReadAllText((Join-Path $here '..\viewer.html'), [Text.Encoding]::UTF8)
$js = "// Generated by deploy.ps1 from ../viewer.html - do not edit.`nexport const VIEWER_HTML = " + (ConvertTo-Json -InputObject $html -Compress) + ";`n"
[IO.File]::WriteAllText((Join-Path $here 'src\viewer.js'), $js, (New-Object Text.UTF8Encoding $false))
$env:WRANGLER_SEND_METRICS = 'false'
Push-Location $here
try { npx --yes wrangler@4 deploy } finally { Pop-Location }
